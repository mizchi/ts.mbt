#!/usr/bin/env node
// Regenerate src/checker/lib_members.mbt: the complete instance-member NAME
// set of a few lib interfaces, unioned across every bundled TS7 lib file
// (`typescript7/tsc/internal/bundled/libs/lib.*.d.ts`).
//
// The checker's member-existence check abstains on an `Applied(Map, …)`
// receiver because it has no `interface Map` declaration to enumerate —
// so `readonlyMap.set(…)`, `readonlyArray.push(…)` and `map.foo` were all
// silent. A name list is enough to decide existence (the types still come
// from the hand-written prototype tables), and the UNION across libs is
// the safe direction: a member some lib declares is never reported, so a
// file compiled against an older lib only loses a finding.
//
// Only interfaces declared WITHOUT an `extends` clause in every lib file
// are listed, because an inherited member would be invisible to this scan.
import fs from "node:fs";
import path from "node:path";

const ROOT = path.resolve(import.meta.dirname, "..");
const LIB = process.env.LIB ?? path.join(ROOT, "typescript7/tsc/internal/bundled/libs");
const OUT = path.join(ROOT, "src/checker/lib_members.mbt");

const WANTED = [
  "Map",
  "ReadonlyMap",
  "Set",
  "ReadonlySet",
  "WeakMap",
  "WeakSet",
  "ReadonlyArray",
];

const members = new Map(WANTED.map((n) => [n, new Set()]));
const extended = new Set();

for (const file of fs.readdirSync(LIB).filter((f) => /^lib\..*\.d\.ts$/.test(f)).sort()) {
  const lines = fs.readFileSync(path.join(LIB, file), "utf8").split("\n");
  let cur = null;
  let depth = 0;
  for (const raw of lines) {
    const line = raw.replace(/\/\/.*$/, "");
    if (cur === null) {
      const m = line.match(/^\s*interface\s+([A-Za-z_$][\w$]*)\s*(<[^{]*>)?\s*(extends[^{]*)?\{/);
      if (m && members.has(m[1])) {
        cur = m[1];
        if (m[3]) extended.add(cur);
        depth = 1;
        if (/\}\s*$/.test(line.slice(line.indexOf("{") + 1))) {
          cur = null;
        }
        continue;
      }
      continue;
    }
    if (depth === 1) {
      const mm = line.match(/^\s*(?:readonly\s+)?(?:\[Symbol\.([A-Za-z]+)\]|([A-Za-z_$][\w$]*))\??\s*[(<:]/);
      if (mm) members.get(cur).add(mm[1] ? `@@${mm[1]}` : mm[2]);
    }
    for (const ch of line) {
      if (ch === "{") depth++;
      else if (ch === "}") depth--;
    }
    if (depth <= 0) cur = null;
  }
}

for (const n of extended) members.delete(n);

let out = `// @generated by scripts/gen_lib_members.mjs — do not edit by hand.
// Instance-member names of lib interfaces, unioned across every bundled
// TS7 lib file. See the generator's header for why a name list suffices.

///|
/// \`Some(true)\` when lib interface \`iface\` declares \`member\` in any lib
/// file, \`Some(false)\` when none does, \`None\` when \`iface\` is not one of
/// the enumerated interfaces (the caller must then abstain).
fn lib_interface_declares_member(iface : String, mem : String) -> Bool? {
  match iface {
`;
for (const [n, set] of members) {
  const names = [...set].sort();
  out += `    "${n}" =>\n      Some(\n        match mem {\n`;
  out += `          ${names.map((x) => JSON.stringify(x)).join(" | ")} => true\n`;
  out += `          _ => false\n        },\n      )\n`;
}
out += `    _ => None\n  }\n}\n`;
fs.writeFileSync(OUT, out);
for (const [n, set] of members) console.log(`${n}: ${set.size}`);
if (extended.size) console.log(`skipped (extends): ${[...extended].join(", ")}`);
